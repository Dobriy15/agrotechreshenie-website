class Command(BaseCommand):
    help = "Наполнить сайт контентом из макета и архива фото"

    def add_arguments(self, parser):
        parser.add_argument("--photos", help="Папка «фото сайт» из архива заказчика")
        parser.add_argument("--reset-photos", action="store_true", help="Пересобрать галереи")

    def handle(self, *args, photos=None, reset_photos=False, **kw):
        s = SiteSettings.load() or SiteSettings()
        s.hero_title = "Высокоточный сервис спецтехники, благоустройство территорий и эко-проекты"
        s.hero_subtitle = (
            "ООО «АгроТехРешение» — ваш надёжный партнёр в Республике Беларусь. "
            "Выполняем профессиональный ремонт узлов машин с выездом к клиенту, убираем и косим "
            "объекты в режиме 24/7, развиваем перспективные направления загородного туризма"
        )
        s.about_html = ABOUT
        s.phone_1, s.phone_2 = "+375296742612", "+375296242612"
        s.production_address = "пер. Софьи Ковалевской 44а"
        s.office_address = "г. Минск, ул. Шатько, 43 ком 20а"
        s.instagram_url = "https://www.instagram.com/agrotexreshenie"
        if not s.hero_image:
            s.hero_image.save("hero.webp", File(open(SEED / "hero.webp", "rb")), save=False)
        s.save()

        Stat.objects.all().delete()
        for i, (v, l) in enumerate(STATS):
            Stat.objects.create(value=v, label=l, order=i)

        Review.objects.all().delete()
        for i, (n, r, t) in enumerate(REVIEWS):
            Review.objects.create(name=n, role=r, text=t, order=i)

        cats = {}
        for i, (slug, title, status, img) in enumerate(CATEGORIES):
            c, _ = Category.objects.get_or_create(slug=slug, defaults={"title": title, "order": i})
            c.title, c.status, c.order = title, status, i
            if not c.image:
                c.image.save(img, File(open(SEED / img, "rb")), save=False)
            c.save()
            cats[slug] = c

        photos_dir = Path(photos) if photos else None
        for i, (cat, slug, title, card, folder, cover, html) in enumerate(SERVICES):
            svc, _ = Service.objects.get_or_create(
                category=cats[cat], slug=slug, defaults={"title": title, "text_html": html}
            )
            svc.title, svc.card_title, svc.text_html, svc.order = title, card, html, i
            svc.save()
            if not photos_dir:
                continue
            card_src = CARD_OVERRIDES.get(slug)
            if card_src and not svc.card_image and (photos_dir / folder / card_src).exists():
                with open(photos_dir / folder / card_src, "rb") as fh:
                    svc.card_image.save(card_src, File(fh), save=False)
                svc.save()
            if svc.media.exists() and not reset_photos:
                continue
            svc.media.all().delete()
            files = sorted(p for p in (photos_dir / folder).iterdir() if p.suffix.lower() in (".jpg", ".jpeg", ".png"))
            files.sort(key=lambda p: p.name != cover)  # обложка первой
            for n, f in enumerate(files):
                m = ServiceMedia(service=svc, order=n)
                with open(f, "rb") as fh:
                    m.image.save(f.name, File(fh), save=False)
                m.save()
                self.stdout.write(f"  {svc.slug}: {f.name}")
            if slug == "vyzhiganie-paltsev" and (SEED / "vyzhiganie.mp4").exists():
                m = ServiceMedia(service=svc, order=1)  # видео вторым слайдом
                m.video.save("vyzhiganie.mp4", File(open(SEED / "vyzhiganie.mp4", "rb")), save=False)
                m.save()
                svc.media.exclude(pk=m.pk).filter(order__gte=1).update(order=F("order") + 1)

        self.stdout.write(self.style.SUCCESS("Готово"))

